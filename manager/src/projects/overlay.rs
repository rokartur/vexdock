/// The compose file the manager writes from the service rows of one
/// environment. It is the only file compose is given: every service is a row.
const OVERLAY_FILE_NAME: &str = "managed.yml";

/// Holds one checkout and one env file per service.
pub(super) const SERVICES_DIR_NAME: &str = "services";

impl Projects {
	/// Where a service keeps its own state, currently its git checkout. One
	/// directory per service, because two services of the same environment can
	/// build from two different repositories.
	pub fn service_dir(&self, env: &Environment, name: &str) -> String {
		format!("{}/{SERVICES_DIR_NAME}/{name}", self.cfg.project_dir(&env.id))
	}

	/// The env file a service hands to its container. Per service so two
	/// Postgres services in one project can each define POSTGRES_PASSWORD.
	pub fn service_env_file_path(&self, env: &Environment, name: &str) -> String {
		format!("{}/{SERVICES_DIR_NAME}/{name}.env", self.cfg.project_dir(&env.id))
	}

	/// Renders every configured service of an environment into its compose file
	/// and writes each service's env file alongside it. Returns the compose file
	/// path, or an empty string when there is nothing to deploy.
	pub fn write_overlay(&self, env: &Environment) -> Result<String> {
		// An application whose source is still unanswered has nothing to render,
		// and emitting an empty service would fail the whole project's deploy.
		let mut managed: Vec<Service> = self
			.db
			.list_services(&env.id)?
			.into_iter()
			.filter(|svc| svc.provider != database::PROVIDER_UNCONFIGURED && !svc.provider.is_empty())
			.collect();
		let path = format!("{}/{OVERLAY_FILE_NAME}", self.cfg.project_dir(&env.id));
		if managed.is_empty() {
			// A stale overlay would resurrect a deleted service on the next deploy.
			ignore_missing(std::fs::remove_file(&path))?;
			return Ok(String::new());
		}
		managed.sort_by(|a, b| a.compose_service_name.cmp(&b.compose_service_name));
		security::create_dir_mode(std::path::Path::new(&format!("{}/{SERVICES_DIR_NAME}", self.cfg.project_dir(&env.id))), 0o750)?;
		let project = self.db.project_by_id(&env.project_id)?;

		let mut body = String::from("# Generated by vexdock. Edits are overwritten on deploy.\nservices:\n");
		let mut volumes = Vec::new();
		for svc in &managed {
			let vars = self.service_variables(&svc.id)?;
			write_env_file(&self.service_env_file_path(env, &svc.compose_service_name), &vars)?;
			let (fragment, vols) =
				self.render_service(env, svc, &vars).map_err(|err| anyhow!("service {}: {err:#}", svc.compose_service_name))?;
			let _ = writeln!(body, "  {}:", svc.compose_service_name);
			// A raw fragment may already name its container; a second key would fail the whole file.
			if !svc.container_name.is_empty() && !svc.compose_fragment.contains("container_name:") {
				let _ = writeln!(body, "    container_name: {}", svc.container_name);
			}
			// Catalog fragments stop on their last content character, so without
			// this the next service's key lands on that line.
			let _ = writeln!(body, "{}", fragment.trim_end_matches('\n'));
			// Compose would name a built image after the p_<ulid> project;
			// pull_policy never keeps compose from looking for it in a registry.
			if database::clones_from_git(&svc.provider) {
				let image = built_image_name(&project.slug, &env.slug, &svc.compose_service_name);
				let _ = writeln!(body, "    image: {image}:latest\n    pull_policy: never");
			}
			// A raw fragment is the user's own YAML; its ports belong in it.
			if svc.provider != database::PROVIDER_RAW {
				let ports = self.db.service_ports(&svc.id)?;
				if !ports.is_empty() {
					body.push_str("    ports:\n");
				}
				for p in ports {
					let _ = writeln!(body, "      - \"{}:{}/{}\"", p.published, p.target, p.protocol);
				}
			}
			volumes.extend(vols);
		}
		if !volumes.is_empty() {
			body.push_str("\nvolumes:\n");
			let mut seen = HashSet::new();
			for v in volumes {
				if seen.insert(v.clone()) {
					let _ = writeln!(body, "  {v}: {{}}");
				}
			}
		}
		// Same temp-and-rename as nginx and acme use: docker compose reads this
		// file, and a half-written one fails the whole project, not one service.
		let tmp = format!("{path}.tmp");
		security::write_file_mode(std::path::Path::new(&tmp), body.as_bytes(), 0o644)?;
		std::fs::rename(&tmp, &path)?;
		Ok(path)
	}

	/// Turns one service row into its compose body, indented four spaces, plus
	/// the named volumes it needs declared at the top level. It is handed the
	/// service's variables because libSQL's namespace switch lives there: sqld
	/// takes it as a flag, so the fragment has to carry it.
	pub(super) fn render_service(&self, env: &Environment, svc: &Service, vars: &[EnvVar]) -> Result<(String, Vec<String>)> {
		let env_file = self.service_env_file_path(env, &svc.compose_service_name);
		match svc.provider.as_str() {
			database::PROVIDER_IMAGE => {}
			p if database::clones_from_git(p) => {}
			database::PROVIDER_RAW => {
				let vols = named_volumes(&svc.compose_fragment)?;
				let fragment = retarget_dot_env(&svc.compose_fragment, &self.env_file_path(env));
				let fragment = with_service_env_file(&fragment, &env_file);
				return Ok((indent(&fragment, 4), vols));
			}
			other => bail!("unknown provider {other:?}"),
		}

		if svc.kind == database::SERVICE_DATABASE {
			// Image and data_path come from the row, not the catalog: the stored
			// reference carries the version the user picked, and re-deriving it
			// from the engine's default tag would move a running database.
			let rendered = engines::render(&engines::Spec {
				engine: svc.engine.clone(),
				name: svc.compose_service_name.clone(),
				image: svc.image.clone(),
				data_path: svc.data_path.clone(),
				env_file,
				sqld: engines::SqldSpec { namespaces: variable(vars, "SQLD_ENABLE_NAMESPACES") == "true", ..Default::default() },
				..Default::default()
			})?;
			let vols = if rendered.volume.is_empty() { Vec::new() } else { vec![rendered.volume] };
			return Ok((rendered.fragment, vols));
		}

		let mut b = String::new();
		if svc.provider == database::PROVIDER_IMAGE {
			let _ = writeln!(b, "    image: {}", engines::validate_image(&svc.image)?);
		} else {
			// Quoted like env_file below: build_path may legally hold a space or a
			// '#', either of which changes which directory compose reads.
			let mut build_context = format!("{}/repository", self.service_dir(env, &svc.compose_service_name));
			if !svc.build_path.is_empty() {
				build_context = security::clean_path(&format!("{build_context}/{}", svc.build_path));
			}
			let _ = write!(b, "    build:\n      context: {}\n", go_quote(&build_context));
			if svc.build_type == database::BUILD_STATIC {
				b.push_str("      dockerfile_inline: |\n");
				b.push_str(&indent(STATIC_DOCKERFILE, 8));
				// A build arg, never spliced into the Dockerfile: the shell only ever sees it quoted.
				if !svc.output_dir.is_empty() {
					let _ = writeln!(b, "      args:\n        OUTPUT_DIR: {}", go_quote(&svc.output_dir));
				}
			} else {
				if !svc.dockerfile.is_empty() {
					let _ = writeln!(b, "      dockerfile: {}", go_quote(&svc.dockerfile));
				}
				if !svc.build_target.is_empty() {
					let _ = writeln!(b, "      target: {}", go_quote(&svc.build_target));
				}
			}
		}
		b.push_str("    restart: unless-stopped\n");
		let _ = writeln!(b, "    env_file: [{}]", go_quote(&env_file));
		let mounts = security::validate_mounts(&svc.mounts)?;
		let mut vols = Vec::new();
		if !mounts.is_empty() {
			b.push_str("    volumes:\n");
			for mount in mounts.lines() {
				let mount = mount.trim();
				let _ = writeln!(b, "      - {mount}");
				vols.push(mount.split(':').next().unwrap_or_default().to_string());
			}
		}
		Ok((b, vols))
	}
}

/// "<project>/<environment>/<service>". Slugs are already valid path
/// components; the service name is folded into lowercase alphanumerics and
/// single dashes, and slashes keep two environments apart.
pub fn built_image_name(project_slug: &str, env_slug: &str, service: &str) -> String {
	let mut b = String::new();
	for r in service.to_lowercase().chars() {
		if r.is_ascii_lowercase() || r.is_ascii_digit() {
			b.push(r);
		} else if !b.is_empty() && !b.ends_with('-') {
			b.push('-');
		}
	}
	format!("{project_slug}/{env_slug}/{}", b.trim_end_matches('-'))
}

/// Runs package.json's build script when there is one, then serves OUTPUT_DIR,
/// or else the first directory holding an index.html, as a single-page app on
/// port 80. $$ is compose's escape for a literal $; .git is never served.
// ponytail: build env comes from nothing but the repo, pass build args if a site needs its variables.
const STATIC_DOCKERFILE: &str = r#"FROM node:lts-slim AS build
COPY --from=oven/bun:1 /usr/local/bin/bun /usr/local/bin/bun
# A prerender preview server binds localhost as ::1 in a build container, then gets fetched on 127.0.0.1.
ENV NODE_OPTIONS=--dns-result-order=ipv4first
WORKDIR /src
COPY . .
RUN if [ -f package.json ] && bun -e 'process.exit(require("./package.json").scripts?.build ? 0 : 1)'; then bun install && bun run build; fi
ARG OUTPUT_DIR
RUN if [ -n "$$OUTPUT_DIR" ]; then cp -r "$$OUTPUT_DIR" /site && rm -rf /site/.git && exit 0; fi; \
    for dir in dist/client dist build out .output/public public .; do \
      if [ -f "$$dir/index.html" ]; then cp -r "$$dir" /site && rm -rf /site/.git && exit 0; fi; \
    done; \
    echo 'no index.html in dist/client, dist, build, out, .output/public, public or the build path' >&2; exit 1

FROM nginx:alpine
COPY --from=build /site /usr/share/nginx/html
RUN echo 'server { listen 80; root /usr/share/nginx/html; location / { try_files $$uri $$uri/ /index.html; } }' > /etc/nginx/conf.d/default.conf
"#;

/// A double-quoted YAML scalar with the escapes Go's %q emits, so the files
/// stay byte-identical to what the Go manager wrote.
pub(super) fn go_quote(s: &str) -> String {
	let mut out = String::from("\"");
	for c in s.chars() {
		match c {
			'"' => out.push_str("\\\""),
			'\\' => out.push_str("\\\\"),
			'\n' => out.push_str("\\n"),
			'\t' => out.push_str("\\t"),
			'\r' => out.push_str("\\r"),
			c if c.is_control() => {
				let _ = write!(out, "\\x{:02x}", c as u32);
			}
			c => out.push(c),
		}
	}
	out.push('"');
	out
}

/// Reads one value out of a service's environment.
fn variable<'a>(vars: &'a [EnvVar], key: &str) -> &'a str {
	vars.iter().find(|v| v.key == key).map(|v| v.value.as_str()).unwrap_or_default()
}

/// Shifts a YAML block so it can sit under a deeper key. Blank lines stay blank
/// rather than becoming trailing whitespace.
pub(super) fn indent(block: &str, spaces: usize) -> String {
	let pad = " ".repeat(spaces);
	let mut out = String::new();
	for line in block.trim_end_matches('\n').split('\n') {
		if !line.trim().is_empty() {
			out.push_str(&pad);
			out.push_str(line);
		}
		out.push('\n');
	}
	out
}

/// Points a fragment's env_file: .env at the project env file, which is what
/// the Environment tab writes.
fn retarget_dot_env(fragment: &str, env_path: &str) -> String {
	let q = go_quote(env_path);
	let mut fragment = fragment.to_string();
	for (from, to) in [
		("- .env".to_string(), format!("- {q}")),
		("- '.env'".into(), format!("- {q}")),
		("- \".env\"".into(), format!("- {q}")),
		("env_file: .env".into(), format!("env_file: {q}")),
		("env_file: [.env]".into(), format!("env_file: [{q}]")),
	] {
		fragment = fragment.replace(&from, &to);
	}
	fragment
}

/// Lists the service's own env file last in the fragment's env_file, so its
/// variables reach the container and win over the project's.
pub(super) fn with_service_env_file(fragment: &str, env_path: &str) -> String {
	let q = go_quote(env_path);
	let mut lines: Vec<String> = fragment.trim_end_matches('\n').split('\n').map(String::from).collect();
	let pad = " ".repeat(fragment_key_indent(&lines).unwrap_or(0));
	let key = format!("{pad}env_file:");
	let Some(i) = lines.iter().position(|line| line.starts_with(&key)) else {
		lines.push(format!("{pad}env_file: [{q}]"));
		return lines.join("\n");
	};
	let rest = &lines[i][key.len()..];
	let rest = rest.split_once(" #").map_or(rest, |(before, _)| before).trim();
	if !rest.is_empty() {
		let mut items = rest.strip_prefix('[').unwrap_or(rest);
		items = items.strip_suffix(']').unwrap_or(items).trim();
		let sep = if items.is_empty() { "" } else { ", " };
		lines[i] = format!("{pad}env_file: [{items}{sep}{q}]");
		return lines.join("\n");
	}
	let mut end = i + 1;
	while end < lines.len() && (lines[end].starts_with(&format!("{pad} ")) || lines[end].starts_with(&format!("{pad}-"))) {
		end += 1;
	}
	let item_pad = if end > i + 1 {
		let next = &lines[i + 1];
		next[..next.len() - next.trim_start_matches(' ').len()].to_string()
	} else {
		pad.clone()
	};
	lines.insert(end, format!("{item_pad}- {q}"));
	lines.join("\n")
}

/// The indentation of a fragment's top-level keys, None when it has none.
fn fragment_key_indent(lines: &[String]) -> Option<usize> {
	lines
		.iter()
		.filter(|line| {
			let trim = line.trim();
			!(trim.is_empty() || trim.starts_with('#') || trim.starts_with('-'))
		})
		.map(|line| line.len() - line.trim_start_matches([' ', '\t']).len())
		.min()
}

fn named_volumes(fragment: &str) -> Result<Vec<String>> {
	let lines: Vec<String> = fragment.split('\n').map(String::from).collect();
	let Some(key_indent) = fragment_key_indent(&lines) else {
		return Ok(Vec::new());
	};
	let mut in_volumes = false;
	let mut names = Vec::new();
	for line in &lines {
		let trim = line.trim();
		if trim.is_empty() || trim.starts_with('#') {
			continue;
		}
		let ind = line.len() - line.trim_start_matches([' ', '\t']).len();
		if ind == key_indent {
			in_volumes = trim.starts_with("volumes:");
			if !in_volumes {
				continue;
			}
			let rest = trim["volumes:".len()..].trim();
			if rest.is_empty() {
				continue;
			}
			in_volumes = false;
			append_named_volume(rest, &mut names)?;
			continue;
		}
		if !in_volumes || ind <= key_indent || !trim.starts_with('-') {
			continue;
		}
		append_named_volume(trim[1..].trim(), &mut names)?;
	}
	Ok(names)
}

fn append_named_volume(entry: &str, names: &mut Vec<String>) -> Result<()> {
	let src = named_volume_source(entry);
	if src.is_empty() {
		return Ok(());
	}
	security::validate_service_name(&src).map_err(|err| anyhow!("volume {src:?}: {err:#}"))?;
	if !names.contains(&src) {
		names.push(src);
	}
	Ok(())
}

fn named_volume_source(entry: &str) -> String {
	let entry = entry.trim().trim_matches(['"', '\'']);
	if entry.is_empty() {
		return String::new();
	}
	if let Some(inner) = entry.strip_prefix('[').and_then(|e| e.strip_suffix(']')) {
		return named_volume_source(inner.trim());
	}
	if entry.starts_with("./") || entry.starts_with('/') || entry.starts_with("~/") {
		return String::new();
	}
	let Some((src, _)) = entry.split_once(':') else {
		return String::new();
	};
	let src = src.trim().trim_matches(['"', '\'']);
	if matches!(src, "" | "type" | "source" | "target" | "read_only") || src.contains('/') {
		return String::new();
	}
	src.to_string()
}
