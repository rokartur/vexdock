//! Renders the reverse-proxy configuration. Users never write Nginx config:
//! they add a domain and the platform generates, validates and reloads.

use std::fmt::Write;

/// One generated vhost: a hostname routed to a container alias on the shared
/// proxy network.
#[derive(Clone, Debug, Default)]
pub struct Upstream {
	pub hostname: String,
	pub alias: String,
	pub port: i64,
	pub https: bool,
	pub redirect_https: bool,
	/// The directory holding fullchain.pem and privkey.pem.
	pub cert_dir: String,
	/// Tried in order against the full request URL.
	pub redirects: Vec<Redirect>,
	/// Turns on auth_basic against auth_file_name(hostname).
	pub basic_auth: bool,
}

/// Answers a request whose URL matches `regex` with a redirect to
/// `replacement`, unless that is the URL already asked for. Both are validated
/// by security::validate_redirect before they get here.
#[derive(Clone, Debug, Default)]
pub struct Redirect {
	pub regex: String,
	pub replacement: String,
	pub permanent: bool,
}

/// The htpasswd file beside a hostname's vhost.
pub fn auth_file_name(hostname: &str) -> String {
	format!("{hostname}.htpasswd")
}

/// Where nginx sees the generated directory.
const GENERATED_ROOT: &str = "/etc/nginx/generated";

/// Where the ACME HTTP-01 tokens are written; Nginx serves it for every
/// hostname so issuance works before a certificate exists.
pub const CHALLENGE_ROOT: &str = "/acme-challenge";

/// The better-auth service, which serves /api/auth.
pub const AUTH_UPSTREAM: &str = "auth:8081";

/// The manager API, reachable from Nginx on the internal network only.
pub const MANAGER_UPSTREAM: &str = "manager:8080";

/// The MCP server, which serves /mcp on the dashboard's hosts.
pub const MCP_UPSTREAM: &str = "mcp:8090";

/// The deterministic config filename for a hostname.
pub fn file_name(hostname: &str) -> String {
	format!("{hostname}.conf")
}

/// The full server block(s) for one upstream.
///
/// proxy_pass goes through a variable plus the Docker embedded resolver so the
/// address is re-resolved at request time: a recreated container gets a new IP
/// and stale caching would otherwise 502 until a reload.
pub fn render(u: &Upstream) -> String {
	let mut b = String::new();
	b.push_str("# generated by the platform - do not edit\n");
	b.push_str("server {\n");
	b.push_str("    listen 80;\n    listen [::]:80;\n");
	let _ = write!(b, "    server_name {};\n\n", u.hostname);
	b.push_str(&challenge_location());

	if u.https && u.redirect_https {
		b.push_str("\n    location / {\n        return 301 https://$host$request_uri;\n    }\n}\n");
	} else {
		b.push('\n');
		b.push_str(&proxy_location(u));
		b.push_str("}\n");
	}

	if !u.https {
		return b;
	}

	b.push_str("\nserver {\n");
	b.push_str("    listen 443 ssl;\n    listen [::]:443 ssl;\n    http2 on;\n");
	let _ = write!(b, "    server_name {};\n\n", u.hostname);
	let _ = writeln!(b, "    ssl_certificate     {}/fullchain.pem;", u.cert_dir);
	let _ = writeln!(b, "    ssl_certificate_key {}/privkey.pem;", u.cert_dir);
	b.push_str("    ssl_protocols TLSv1.2 TLSv1.3;\n");
	b.push_str("    ssl_session_cache shared:SSL:10m;\n");
	b.push_str("    ssl_session_timeout 1d;\n\n");
	b.push_str(&challenge_location());
	b.push('\n');
	b.push_str(&proxy_location(u));
	b.push_str("}\n");
	b
}

/// The redirects and basic auth of a proxied location. Both stay out of the
/// ACME location so issuance keeps working behind them. A redirect whose result
/// equals the request URL is skipped, so a www preset does not loop.
fn access_rules(u: &Upstream) -> String {
	let mut b = String::new();
	if u.basic_auth {
		b.push_str("        auth_basic \"Restricted\";\n");
		let _ = writeln!(b, "        auth_basic_user_file {GENERATED_ROOT}/{};", auth_file_name(&u.hostname));
	}
	if !u.redirects.is_empty() {
		b.push_str("        set $redirect_url $scheme://$host$request_uri;\n");
	}
	for r in &u.redirects {
		let status = if r.permanent { 301 } else { 302 };
		b.push_str("        set $redirect_to \"\";\n");
		let _ = writeln!(b, "        if ($redirect_url ~ \"{}\") {{ set $redirect_to \"{}\"; }}", r.regex, r.replacement);
		b.push_str("        if ($redirect_to = $redirect_url) { set $redirect_to \"\"; }\n");
		let _ = writeln!(b, "        if ($redirect_to) {{ return {status} $redirect_to; }}");
	}
	if !b.is_empty() {
		b.push('\n');
	}
	b
}

fn challenge_location() -> String {
	format!(
		"    location ^~ /.well-known/acme-challenge/ {{\n        root {CHALLENGE_ROOT};\n        default_type \"text/plain\";\n    }}\n"
	)
}

// Every upstream is behind this proxy, so every location hands the original
// request details on.
const FORWARDED_HEADERS: &str = concat!(
	"        proxy_set_header Host $http_host;\n",
	"        proxy_set_header X-Real-IP $remote_addr;\n",
	"        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n",
	"        proxy_set_header X-Forwarded-Proto $scheme;\n",
);

fn proxy_location(u: &Upstream) -> String {
	let mut b = String::new();
	b.push_str("    location / {\n");
	b.push_str(&access_rules(u));
	b.push_str("        resolver 127.0.0.11 valid=1s ipv6=off;\n");
	let _ = writeln!(b, "        set $upstream http://{}:{};", u.alias, u.port);
	b.push_str("        proxy_pass $upstream;\n\n");
	b.push_str("        proxy_http_version 1.1;\n\n");
	b.push_str(FORWARDED_HEADERS);
	b.push('\n');
	b.push_str("        proxy_set_header Upgrade $http_upgrade;\n");
	b.push_str("        proxy_set_header Connection $connection_upgrade;\n\n");
	// SSE and long-poll endpoints must not be buffered or timed out early.
	b.push_str("        proxy_buffering off;\n");
	b.push_str("        proxy_cache off;\n");
	b.push_str("        proxy_read_timeout 3600s;\n");
	b.push_str("        proxy_send_timeout 3600s;\n");
	b.push_str("    }\n");
	b
}

/// Exposes the panel itself on a user-chosen hostname, serving the static UI
/// and proxying /api to the manager.
pub fn render_dashboard(hostname: &str, manager_addr: &str, web_root: &str, https: bool, cert_dir: &str) -> String {
	let mut b = String::new();
	b.push_str("# generated by the platform - dashboard vhost\n");
	b.push_str("server {\n    listen 80;\n    listen [::]:80;\n");
	let _ = write!(b, "    server_name {hostname};\n\n");
	b.push_str(&challenge_location());
	if https {
		b.push_str("\n    location / {\n        return 301 https://$host$request_uri;\n    }\n}\n\n");
		b.push_str("server {\n    listen 443 ssl;\n    listen [::]:443 ssl;\n    http2 on;\n");
		let _ = write!(b, "    server_name {hostname};\n\n");
		let _ = writeln!(b, "    ssl_certificate     {cert_dir}/fullchain.pem;");
		let _ = writeln!(b, "    ssl_certificate_key {cert_dir}/privkey.pem;");
		b.push_str("    ssl_protocols TLSv1.2 TLSv1.3;\n\n");
	} else {
		b.push('\n');
	}
	b.push_str(&dashboard_body(manager_addr, web_root));
	b.push_str("}\n");
	b
}

fn dashboard_body(manager_addr: &str, web_root: &str) -> String {
	let mut b = String::new();
	let _ = writeln!(b, "    root {web_root};");
	b.push_str("    index index.html;\n\n");

	// Credential endpoints are throttled here too. Moving the panel to its own
	// domain must not quietly drop the login limit that :3000 has.
	b.push_str("    location ~ ^/api/auth/(sign-in|sign-up|forget-password|reset-password) {\n");
	b.push_str("        limit_req zone=login_limit burst=5 nodelay;\n");
	let _ = writeln!(b, "        proxy_pass http://{AUTH_UPSTREAM};");
	b.push_str("        proxy_http_version 1.1;\n");
	b.push_str(FORWARDED_HEADERS);
	b.push_str("    }\n\n");

	// Authentication is a separate service; everything else is the manager.
	b.push_str("    location /api/auth/ {\n");
	b.push_str("        limit_req zone=api_limit burst=60 nodelay;\n");
	let _ = writeln!(b, "        proxy_pass http://{AUTH_UPSTREAM};");
	b.push_str("        proxy_http_version 1.1;\n");
	b.push_str(FORWARDED_HEADERS);
	b.push_str("    }\n\n");

	b.push_str("    location /api/ {\n");
	b.push_str("        limit_req zone=api_limit burst=60 nodelay;\n");
	let _ = writeln!(b, "        proxy_pass http://{manager_addr};");
	b.push_str("        proxy_http_version 1.1;\n");
	b.push_str(FORWARDED_HEADERS);
	b.push_str("        proxy_set_header Upgrade $http_upgrade;\n");
	b.push_str("        proxy_set_header Connection $connection_upgrade;\n");
	b.push_str("        proxy_buffering off;\n");
	b.push_str("        proxy_read_timeout 3600s;\n");
	b.push_str("    }\n\n");
	b.push_str("    location = /mcp {\n");
	b.push_str("        limit_req zone=api_limit burst=60 nodelay;\n");
	let _ = writeln!(b, "        proxy_pass http://{MCP_UPSTREAM};");
	b.push_str("        proxy_http_version 1.1;\n");
	b.push_str(FORWARDED_HEADERS);
	b.push_str("        proxy_buffering off;\n");
	b.push_str("        proxy_read_timeout 3600s;\n");
	b.push_str("    }\n\n");
	// OAuth discovery for MCP clients; the other OAuth endpoints are under /api/.
	b.push_str("    location ^~ /.well-known/oauth- {\n");
	b.push_str("        limit_req zone=api_limit burst=60 nodelay;\n");
	let _ = writeln!(b, "        proxy_pass http://{manager_addr};");
	b.push_str("        proxy_http_version 1.1;\n");
	b.push_str(FORWARDED_HEADERS);
	b.push_str("    }\n\n");
	// The OAuth consent screen is one click from a grant, so no page may frame it.
	b.push_str("    location / {\n");
	b.push_str("        add_header X-Frame-Options \"DENY\" always;\n");
	b.push_str("        add_header Content-Security-Policy \"frame-ancestors 'none'\" always;\n");
	b.push_str("        try_files $uri $uri/ /index.html;\n    }\n");
	b
}

/// The stable network alias for one compose service of one environment. Keyed
/// on the environment because production and staging can both run a "web", and
/// a shared alias would send traffic to whichever attached last.
pub fn alias(environment_id: &str, service: &str) -> String {
	let safe: String = service
		.chars()
		.map(|r| match r {
			'a'..='z' | '0'..='9' | '-' => r,
			'A'..='Z' => r.to_ascii_lowercase(),
			_ => '-',
		})
		.collect();
	format!("p_{}_{safe}", environment_id.to_lowercase())
}

/// An nginx {SSHA} hash: base64 of SHA-1(password+salt) followed by the salt.
/// nginx checks it on every request, so a slow hash would cost CPU on each one.
pub fn hash_password(password: &str) -> String {
	use base64::Engine;
	use rand::RngCore;
	use sha1::{Digest, Sha1};
	let mut salt = [0u8; 8];
	rand::thread_rng().fill_bytes(&mut salt);
	let mut hasher = Sha1::new();
	hasher.update(password.as_bytes());
	hasher.update(salt);
	let mut out = hasher.finalize().to_vec();
	out.extend_from_slice(&salt);
	format!("{{SSHA}}{}", base64::engine::general_purpose::STANDARD.encode(out))
}
